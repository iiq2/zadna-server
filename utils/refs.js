/** الأرقام العربية إلى لاتينية، ثم إسقاط كل ما ليس رقماً أو حرفاً. */
function normRef(s) {
  return String(s || '')
    .replace(/[٠-٩]/g, d => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)))
    .replace(/[۰-۹]/g, d => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)))   // فارسية أيضاً — بعض الأجهزة ترسلها
    .replace(/[^0-9A-Za-z]/g, '')
    .toUpperCase()
    .slice(0, 60);
}

module.exports = { normRef };
