/* ============================================================
   رقم الجوال — صيغة واحدة تُكتب بها وتُقارن.

   هذا الملفّ يُنهي عائلةً كاملة من الأعطال، وكلّها من سببٍ واحد:
   الرقم الواحد يُخزَّن بأربع صور، والمقارنة حرفية.

     0599123456 · +970599123456 · 00970599123456 · 059-912-3456

   أربعةُ نصوص، وشخصٌ واحد. وما نتج عن ذلك خلال هذا المشروع:
     · طلبات تختفي من سجلّ صاحبها فيظنّ أننا حذفناها
     · إشعارات لا تصل ولا يُسجَّل لها خطأ — لا الزبون يعلم ولا نحن
     · مندوب يُردّ عن شات طلبه هو
     · محفظة مندوب لا تُجلب لأن مفتاحه لم يُطابَق

   وكان الحلّ الجزئي دائماً: `samePhone` تُطبّع **عند المقارنة**.
   وهذا يُصلح القراءة ولا يُصلح المصدر — فيبقى كل نداء جديد عرضةً
   للعطل نفسه ما دام التخزين غير موحَّد.

   القاعدة هنا: **يُطبَّع عند الكتابة، مرّة واحدة، فلا يبقى ما يُقارَن.**

   والصيغة المعتمدة هي المحلية `05xxxxxxxx` — لأنها ما يكتبه الناس،
   وما يظهر في هواتفهم، وما يُطبع على بطاقات المطاعم.
   ============================================================ */

/**
 * يُحوّل أي صيغة إلى الصيغة المحلية `05xxxxxxxx`.
 * يُرجع نصّاً فارغاً إن لم يكن فيه أرقام.
 */
function normPhone(raw) {
  let s = String(raw == null ? '' : raw)
    /* أرقام عربية-هندية أولاً: من يكتب رقمه بلوحة مفاتيح عربية يُدخل
     * ٠٥٩٩… — وكانت تسقط كلّها في `replace(/\D/g)` فيُرجع فراغاً،
     * فيبدو الحساب بلا رقم ولا يُطابق نفسه. */
    .replace(/[٠-٩]/g, d => String(d.charCodeAt(0) - 0x0660))
    .replace(/[۰-۹]/g, d => String(d.charCodeAt(0) - 0x06F0))
    /* ثم المحارف غير المرئية: علامات الاتجاه ومسافة غير الفاصلة تُنسخ
     * مع الرقم من جهات الاتصال وواتساب بلا أن يراها أحد. وهي ليست ضمن
     * `\s` في JavaScript — فكان الرقم يبدأ بمحرفٍ خفيّ، فلا يُطابق
     * `^\+?970` ويُطبَّع خطأً إلى `0970599…` بدل `0599…`. رقمان لصاحبٍ
     * واحد يصيران رقمين مختلفين، وهو أصل التكرار الذي نطارده. */
    .replace(/[​-‏‪-‮⁦-⁩﻿ ]/g, '')
    .replace(/[\s\-()]/g, '');
  if (!s) return '';
  // مفاتيح الدولة: فلسطين 970 وإسرائيل 972 — كلاهما مستعمل في الضفة
  s = s.replace(/^\+?9(70|72)/, '').replace(/^009(70|72)/, '');
  s = s.replace(/\D/g, '');
  if (!s) return '';
  if (!s.startsWith('0')) s = '0' + s;
  return s;
}

/* 059 و056 فلسطينية، و050/052/053/054/055/058 إسرائيلية يستعملها كثيرون
 * في الضفة. القاعدة نفسها في التطبيق (PhoneValidator) — ولا يجوز أن يكون
 * السيرفر أضيق منه: قَبِلَ الطلبَ ثم رفض حفظ رقم صاحبه، فبقي الزبون بلا
 * رقم في حسابه بلا سبب ظاهر. */
const MOBILE_RE = /^(059|056|050|052|053|054|055|058)\d{7}$/;

/** هل هو رقم جوال صالح بعد التطبيع؟ */
function isValidMobile(raw) {
  return MOBILE_RE.test(normPhone(raw));
}

/**
 * هل الرقمان لشخصٍ واحد؟ يبقى للمقارنة مع البيانات القديمة التي
 * كُتبت قبل توحيد التخزين — ولا يُستغنى عنه حتى تُطبَّع كلّها.
 */
function samePhone(a, b) {
  const x = normPhone(a), y = normPhone(b);
  return !!x && x === y;
}

module.exports = { normPhone, isValidMobile, samePhone, MOBILE_RE };
